# Шаг 4. Разбор текста пользователя (только встроенные средства)
def разобрать_запрос(текст):
    текст_нижний = текст.lower()
    
    # Определяем действие
    действие = "неизвестно"
    if "утечка" in текст_нижний or "потеря" in текст_нижний or "взлом" in текст_нижний or "украли" in текст_нижний:
        действие = "происшествие"
    elif "передат" in текст_нижний or "передач" in текст_нижний or "отправить" in текст_нижний:
        действие = "передача"
        
    # Ищем страну
    найденая_страна = None
    код_страны = None
    for код, инфо in страны.items():
        if инфо["название"].lower() in текст_нижний:
            найденая_страна = инфо["название"]
            код_страны = код
            break
            
    # Ищем число людей (извлекаем все цифры)
    числа = re.findall(r'\d+', текст.replace(' ', ''))
    число_людей = int(числа[0]) if числа else 0
    
    # Ищем вид данных
    вид_данных = "иные"
    if "биометри" in текст_нижний or "голос" in текст_нижний:
        вид_данных = "биометрические"
    elif "медицин" in текст_нижний or "здоров" in текст_нижний:
        вид_данных = "специальные"
    elif "паспорт" in текст_нижний or "фио" in текст_нижний:
        вид_данных = "общедоступные"
        
    return {
        "действие": действие,
        "страна": найденая_страна,
        "код_страны": код_страны,
        "число_людей": число_людей,
        "вид_данных": вид_данных,
        "исходный_текст": текст
    }

# Шаг 5. Формирование отчета
def сформировать_отчет(запрос, результаты_документов):
    путь_отчета = os.path.join("отчеты", "итоговый_отчёт.txt")
    os.makedirs("отчеты", exist_ok=True)
    
    with open(путь_отчета, "w", encoding="utf-8") as ф:
        ф.write("ИТОГОВЫЙ ОТЧЕТ О СООТВЕТСТВИИ ТРЕБОВАНИЯМ 152-ФЗ\n")
        ф.write("="*60 + "\n\n")
        
        # 1. Общие сведения
        ф.write("1. ОБЩИЕ СВЕДЕНИЯ ОБ ОРГАНИЗАЦИИ\n")
        ф.write(f"Название: {паспорт_организации['название']}\n")
        ф.write(f"Отрасль: {паспорт_организации['отрасль']}\n")
        ф.write(f"Выручка: {паспорт_организации['годовая_выручка_в_рублях']} руб.\n")
        ф.write(f"Данных в базе: {паспорт_организации['количество_человек_в_базе']} чел.\n\n")
        
        # 2. Итоги проверки документов
        ф.write("2. ИТОГИ ПРОВЕРКИ ДОКУМЕНТОВ\n")
        общий_штраф_док = 0
        for док, рез in результаты_документов.items():
            статус = "В порядке" if рез["правильный_ли_документ"] else "Грубая ошибка"
            ф.write(f"- {док}: {статус}. {рез['пояснение']}\n")
            if рез["штраф_в_рублях"] > 0:
                ф.write(f"  Размер штрафа: {рез['штраф_в_рублях']} руб.\n")
            общий_штраф_док += рез["штраф_в_рублях"]
        ф.write("\n")
        
        # 3. Найденные нарушения (Шаг 3)
        ф.write("3. НАЙДЕННЫЕ НАРУШЕНИЯ\n")
        общий_штраф_нар = 0
        выручка = паспорт_организации['годовая_выручка_в_рублях']
        for нар in нарушения["список_нарушений"]:
            # Пересчитываем штраф через наш калькулятор
            if "биометр" in нар["описание_нарушения"].lower():
                вид_нар = "биометрия"
            elif "согласие" in нар["описание_нарушения"].lower():
                вид_нар = "нарушение_согласия"
            else:
                вид_нар = "утечка_малая"
                
            расчет = рассчитать_штраф(вид_нар, 1000, False, выручка)
            ф.write(f"- Нарушение №{нар['номер']}: {нар['описание_нарушения']}\n")
            ф.write(f"  Правовое основание: {нар['норма_права']}\n")
            ф.write(f"  Штраф: от {расчет['мин_штраф']} до {расчет['макс_штраф']} руб.\n")
            общий_штраф_нар += расчет["макс_штраф"]
        ф.write("\n")
        
        # 4. Разбор запроса пользователя
        ф.write("4. РАЗБОР ЗАПРОСА ПОЛЬЗОВАТЕЛЯ\n")
        ф.write(f"Исходный текст: '{запрос['исходный_текст']}'\n")
        ф.write(f"Действие: {запрос['действие']}\n")
        ф.write(f"Страна: {запрос['страна'] or 'Не указана'}\n")
        ф.write(f"Число людей: {запрос['число_людей']}\n")
        ф.write(f"Вид данных: {запрос['вид_данных']}\n")
        
        if запрос['страна'] and запрос['действие'] == "передача":
            инфо_по_стране = проверить_страну(запрос['код_страны'])
            ф.write(f"Приговор по стране: {инфо_по_стране['приговор']}\n")
            if инфо_по_стране['условия']:
                ф.write("Условия передачи:\n")
                for усл in инфо_по_стране['условия']:
                    ф.write(f"  - {усл}\n")
            ф.write(f"Ссылки на закон: {', '.join(инфо_по_стране['ссылки_на_закон'])}\n")
        ф.write("\n")
        
        # 5. Итоговая оценка
        ф.write("5. ИТОГОВАЯ ОЦЕНКА\n")
        итоговый_риск = общий_штраф_док + общий_штраф_нар
        # Вес нарушения: 10 баллов за документ, 15 за нарушение
        штрафные_баллы = (len(результаты_документов) * 10) + (len(нарушения["список_нарушений"]) * 15)
        оценка = max(0, 100 - штрафные_баллы)
        
        ф.write(f"Оценка соответствия: {оценка} из 100\n")
        ф.write(f"Общий риск штрафов: {итоговый_риск:,} руб.\n".replace(',', ' '))
        ф.write("Первоочередные действия:\n")
        ф.write("1. Оформить согласие клиента как отдельный документ.\n")
        ф.write("2. Перенести биометрические данные в ЕБС.\n")
        ф.write("3. Уничтожить просроченные справки о здоровье.\n")
        ф.write("4. Провести инструктаж с HR по проверке ЭП.\n")
        ф.write("5. Внедрить обязательное уведомление РКН о передаче данных.\n")

# Функция для разговорного цикла (Шаг 6)
def запустить_симулятор():
    загрузить_артефакты()
    
    print("\n--- СИМУЛЯТОР ПРОВЕРКИ ЗАКОНОДАТЕЛЬСТВА О ПДН ---")
    print("Здравствуйте! Я готов проанализировать вашу ситуацию.")
    print("Введите ситуацию (например: 'Хотим передать данные 20000 клиентов в Китай' или 'Утечка 5000 голосовых данных').")
    print("Для выхода напишите 'выход'.\n")
    
    # Первичная проверка документов (Шаг 2)
    рез_документов = {}
    папка_док = os.path.join("данные", "документы")
    if os.path.exists(папка_док):
        for файл in os.listdir(папка_док):
            if "согласие" in файл and файл.endswith(".txt"):
                с_текстом = open(os.path.join(папка_док, файл), "r", encoding="utf-8").read()
                тип = "клиент" if "клиента" in файл else "сотрудник"
                рез_документов[файл] = проверить_согласие(с_текстом, тип)
            
    while True:
        запрос_текст = input("\nВаш запрос: ")
        if запрос_текст.lower() in ["выход", "exit", "quit"]:
            print("Завершение работы симулятора. До свидания!")
            break
            
        разобранный_запрос = разобрать_запрос(запрос_текст)
        сформировать_отчет(разобранный_запрос, рез_документов)
        
        print(f"✅ Отчет обновлен! (Действие: {разобранный_запрос['действие']}, Страна: {разобранный_запрос['страна'] or 'Не указана'})")
        print(f"Подробности смотрите в файле: отчеты/итоговый_отчёт.txt")

