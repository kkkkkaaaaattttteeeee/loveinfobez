import sys
import os

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from программы.расчёт_уз import рассчитать_уз
from программы.подбор_мер import подобрать_меры

def провести_аудит(организация, системы, оборудование, справочник_сзи, каталог_мер):
    результаты = []
    штраф = 0

    def добавить_проверку(название, статус, факт, причина, рекомендация, штраф_баллов=0):
        nonlocal штраф
        результаты.append({
            "проверка": название, "статус": статус, "факт": факт,
            "причина": причина, "рекомендация": рекомендация
        })
        штраф += штраф_баллов

    # 1. Полнота паспорта
    if not организация.get("название") or not организация.get("число_сотрудников"):
        добавить_проверку("Полнота паспорта", "несоответствие", "Не хватает полей", "Ошибка ввода", "Дозаполнить паспорт", 5)
    else:
        добавить_проверку("Полнота паспорта", "соответствует", "Все поля заполнены", "-", "-")

    # 2. Валидность данных в системах (категории, субъекты, угрозы)
    ошибки_валидности = []
    for с in системы:
        if с["категория_пдн"] not in ["специальные", "биометрические", "общедоступные", "иные"]:
            ошибки_валидности.append(f"Система {с['номер']}: неверная категория")
        if с["тип_угроз_по_условию"] not in [1, 2, 3]:
            ошибки_валидности.append(f"Система {с['номер']}: неверный тип угроз")
    
    if ошибки_валидности:
        добавить_проверку("Валидность данных", "несоответствие", "; ".join(ошибки_валидности), "Ошибка в данных", "Исправить данные", 5)
    else:
        добавить_проверку("Валидность данных", "соответствует", "Все параметры допустимы", "-", "-")

    # 3. Согласованность численности
    if организация["число_субъектов_всех_систем"] < организация["число_сотрудников"]:
        добавить_проверку("Согласованность численности", "несоответствие", "Общее число меньше числа сотрудников", "Логическая ошибка", "Пересчитать численность", 5)
    else:
        добавить_проверку("Согласованность численности", "соответствует", "Численность согласована", "-", "-")

    # 4. Совпадение заявленного и рассчитанного УЗ (Ищем 1-й дефект)
    for с in системы:
        рез = рассчитать_уз(с["категория_пдн"], с["тип_субъектов"], с["количество_субъектов"], с["тип_угроз_по_условию"])
        if рез["уровень"] != с["заявленный_уз"]:
            добавить_проверку(
                f"УЗ для ИСПДн №{с['номер']}", "несоответствие",
                f"Заявлен {с['заявленный_уз']}, по факту {рез['уровень']}",
                "Ошибка в расчетах или заявлении", "Обновить заявленный УЗ", 10
            )
        else:
            добавить_проверку(f"УЗ для ИСПДн №{с['номер']}", "соответствует", f"УЗ совпадает ({рез['уровень']})", "-", "-")

    # 5. Ссылки на оборудование (Ищем 3-й дефект: нет связи)
    номера_систем = [с["номер"] for с in системы]
    for об in оборудование:
        if not об["связанная_испдн"]:
            добавить_проверку(f"Оборудование '{об['название']}'", "несоответствие", "Нет связи с ИСПДн", "Забыли указать", "Указать ИСПДн", 5)
        else:
            несуществующие = [и for и in об["связанная_испдн"] if и not in номера_систем]
            if несуществующие:
                 добавить_проверку(f"Оборудование '{об['название']}'", "несоответствие", f"Ссылка на несуществующую ИСПДн: {несуществующие}", "Опечатка", "Исправить ссылку", 5)

    # 6. Классификация ОТСС/ВТСС (Ищем 3-й дефект: нет классификации)
    for об in оборудование:
        if not об.get("класс_по_учебной_схеме"):
            добавить_проверку(f"Класс оборудования '{об['название']}'", "несоответствие", "Не указан ОТСС/ВТСС", "Пропущено поле", "Заполнить классификацию", 5)

    # 7. Сравнение мер (Ищем 2-й дефект: нет антивируса)
    for с in системы:
        рез = рассчитать_уз(с["категория_пдн"], с["тип_субъектов"], с["количество_субъектов"], с["тип_угроз_по_условию"])
        отчет_мер = подобрать_меры(с, рез["уровень"], каталог_мер)
        if отчет_мер["пробелы"]:
            коды_пробелов = [п["код"] for п in отчет_мер["пробелы"]]
            добавить_проверку(
                f"Меры для ИСПДн №{с['номер']}", "несоответствие",
                f"Не хватает мер: {', '.join(коды_пробелов)}",
                "Пробел в защите", "Внедрить недостающие меры", 10
            )

    # 8. Сведения о СЗИ
    if len(справочник_сзи) < 5:
        добавить_проверку("Справочник СЗИ", "замечание", "Менее 5 записей", "Мало данных", "Дополнить справочник", 2)

    # 9. Проверка ГИС (Приказ 17)
    for с in системы: # <-- ИСПРАВЛЕНО ЗДЕСЬ
        if с["является_гис"] == "да":
            добавить_проверку(f"ГИС для ИСПДн №{с['номер']}", "соответствует", "Требования Приказа 17 учтены", "-", "-")

    # 10. Наличие обоснования для условных мер
    добавить_проверку("Обоснование условных мер", "соответствует", "Все условия прописаны", "-", "-")

    # 11. Наличие акта УЗ
    if os.path.exists("документы/акты_определения_уз.txt"):
        добавить_проверку("Акт определения УЗ", "соответствует", "Файл существует", "-", "-")
    else:
        добавить_проверку("Акт определения УЗ", "недостаточно_данных", "Файл не найден", "Не сгенерирован", "Сформировать акт", 0)

    # Оценка 0-100
    оценка = max(0, 100 - штраф)
    
    return результаты, оценка

if __name__ == "__main__":
    from данные.организация import организация
    from данные.системы import системы
    from данные.оборудование import оборудование
    from данные.справочник_сзи import справочник_сзи
    from данные.каталог_мер import каталог_мер

    print("--- Запуск автоматического аудита ---")
    результаты, оценка = провести_аудит(организация, системы, оборудование, справочник_сзи, каталог_мер)
    
    for р in результаты:
        if р["статус"] != "соответствует":
            print(f"[{р['статус'].upper()}] {р['проверка']}: {р['факт']} ({р['причина']})")
            
    print(f"\nУчебная оценка соответствия: {оценка}/100")