def сформировать_акт_уз():
    os.makedirs("документы", exist_ok=True)
    дата = datetime.now().strftime("%d.%m.%Y")
    with open("документы/акты_определения_уз.txt", "w", encoding="utf-8") as f:
        f.write(f"АКТ ОПРЕДЕЛЕНИЯ УРОВНЯ ЗАЩИЩЕННОСТИ ИСПДн (Дата: {дата})\n" + "="*60 + "\n\n")
        for с in системы:
            рез = рассчитать_уз(с["категория_пдн"], с["тип_субъектов"], с["количество_субъектов"], с["тип_угроз_по_условию"])
            f.write(f"ИСПДн №{с['номер']} ({с['название']}):\n")
            f.write(f"  Входные параметры: Категория={с['категория_пдн']}, Субъекты={с['тип_субъектов']} ({с['количество_субъектов']}), Угрозы={с['тип_угроз_по_условию']}\n")
            f.write(f"  Рассчитанный УЗ: {рез['уровень']}\n  Обоснование: {рез['обоснование']}\n")
            f.write(f"  Заявленный УЗ: {с['заявленный_уз']}\n")
            if с['заявленный_уз'] != рез['уровень']: f.write(f"  ВНИМАНИЕ: Расхождение!\n")
            f.write("-" * 50 + "\n")
    print("[OK] Акт определения УЗ сформирован.")

def сформировать_план_мер_и_тз():
    os.makedirs("документы", exist_ok=True)
    with open("документы/план_мер.txt", "w", encoding="utf-8") as f:
        f.write("ПЛАН МЕРОПРИЯТИЙ ПО ЗАЩИТЕ ПДн\n" + "="*50 + "\n\n")
        for с in системы:
            рез = рассчитать_уз(с["категория_пдн"], с["тип_субъектов"], с["количество_субъектов"], с["тип_угроз_по_условию"])
            отчет_мер = подобрать_меры(с, рез["уровень"], каталог_мер)
            f.write(f"ИСПДн №{с['номер']} ({с['название']}) - Требуемый УЗ: {рез['уровень']}\n")
            for мера in отчет_мер["требуемые_меры"]:
                f.write(f" - {мера}\n")
            f.write("\n")

    with open("документы/тз_на_сзпдн.txt", "w", encoding="utf-8") as f:
        f.write("ТЕХНИЧЕСКОЕ ЗАДАНИЕ НА СИСТЕМУ ЗАЩИТЫ ПДн\n" + "="*50 + "\n\n")
        f.write(f"1. Организация: {организация['название']}\n")
        f.write("2. Цель: Обеспечение безопасности ПДн (ФЗ-152, ПП-1119).\n")
        f.write("3. Требования к СЗИ: Наличие сертификатов ФСТЭК/ФСБ.\n")
        f.write("4. Этапы: 1. Аудит. 2. Закупка. 3. Настройка. 4. Приемка.\n")
        f.write("5. Критерии приемки: Устранение всех несоответствий.\n")
    print("[OK] План мер и ТЗ сформированы.")

def сформировать_промежуточные_отчеты():
    os.makedirs("отчёты", exist_ok=True)
    # Отчет по уровням
    with open("отчёты/отчёт_по_уровням.txt", "w", encoding="utf-8") as f:
        for с in системы:
            рез = рассчитать_уз(с["категория_пдн"], с["тип_субъектов"], с["количество_субъектов"], с["тип_угроз_по_условию"])
            f.write(f"ИСПДн {с['номер']} ({с['название']}): {рез['уровень']}\n")
    # Отчет по мерам
    with open("отчёты/отчёт_по_мерам.txt", "w", encoding="utf-8") as f:
        for с in системы:
            рез = рассчитать_уз(с["категория_пдн"], с["тип_субъектов"], с["количество_субъектов"], с["тип_угроз_по_условию"])
            отчет_мер = подобрать_меры(с, рез["уровень"], каталог_мер)
            f.write(f"ИСПДн {с['номер']}: Пробелы: {len(отчет_мер['пробелы'])} мер\n")
    print("[OK] Промежуточные отчеты (уровни, меры) сформированы.")

def сформировать_план_исправлений():
    with open("документы/план_исправлений.txt", "w", encoding="utf-8") as f:
        f.write("ПЛАН ИСПРАВЛЕНИЙ\n\n")
        приоритет = 1
        for с in системы:
            рез = рассчитать_уз(с["категория_пдн"], с["тип_субъектов"], с["количество_субъектов"], с["тип_угроз_по_условию"])
            отчет_мер = подобрать_меры(с, рез["уровень"], каталог_мер)
            for пробел in отчет_мер["пробелы"]:
                f.write(f"{приоритет}. ИСПДн №{с['номер']}: Внедрить {пробел['код']} ({пробел['название']})\n")
                приоритет += 1
        f.write(f"{приоритет}. Оборудование: Указать ОТСС/ВТСС для 'Принтер HP в СПА'\n")
        f.write(f"{приоритет+1}. ИСПДн №1: Обновить УЗ (УЗ-3 -> УЗ-4)\n")
    print("[OK] План исправлений сформирован.")

def сформировать_итоговый_отчет():
    результаты_аудита, оценка = провести_аудит(организация, системы, оборудование, справочник_сзи, каталог_мер)
    with open("отчёты/отчёт_аудита.txt", "w", encoding="utf-8") as f:
        for р in результаты_аудита:
            f.write(f"[{р['статус'].upper()}] {р['проверка']}: {р['факт']}\n")
    with open("отчёты/итоговый_отчёт.txt", "w", encoding="utf-8") as f:
        f.write(f"ИТОГОВЫЙ ОТЧЕТ. Организация: {организация['название']}\n")
        f.write(f"Учебная оценка: {оценка}/100\n")
        f.write("Все детали в прилагаемых документах и отчетах.\n")
    print("[OK] Итоговый отчет и отчет аудита сформированы.")

def main():
    print("ГЛАВНЫЙ СИМУЛЯТОР")
    while True:
        print("\nКоманды: все | система <номер> | сценарий <номер> | сценарий импорт | выход")
        команда = input("Введите команду: ").strip().lower().split()
        if not команда: continue
        if команда[0] == "выход": break
        elif команда[0] == "все":
            сформировать_акт_уз()
            сформировать_план_мер_и_тз()
            сформировать_промежуточные_отчеты()
            сформировать_план_исправлений()
            сформировать_итоговый_отчет()
            print("\nВсе документы и отчеты успешно созданы!")
        elif команда[0] == "система" and len(команда) > 1:
            с = next((x for x in системы if str(x["номер"]) == str(команда[1])), None)
            if с:
                рез = рассчитать_уз(с["категория_пдн"], с["тип_субъектов"], с["количество_субъектов"], с["тип_угроз_по_условию"])
                print(f"ИСПДн №{с['номер']}. УЗ: {рез['уровень']}")
        elif команда[0] == "сценарий" and len(команда) > 1:
            if команда[1] == "импорт": сформировать_акт_уз()
            else:
                сцен = next((x for x in тестовые_сценарии if str(x["номер"]) == str(команда[1])), None)
                if сцен:
                    рез = рассчитать_уз(сцен["категория"], сцен["тип_субъектов"], сцен["количество"], сцен["тип_угроз"])
                    print(f"Сценарий {сцен['номер']}: {рез['уровень']}")

if __name__ == "__main__":
    main()