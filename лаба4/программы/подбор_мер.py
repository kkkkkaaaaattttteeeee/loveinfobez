def подобрать_меры(система, уровень, каталог_мер):
    требуемые = []
    фактические = система.get("фактические_меры", [])
    пробелы = []
    проверка_гиc_17 = "Не применимо"

    # Проходим по каждой мере в каталоге
    for мера in каталог_мер:
        # Если мера требуется для текущего уровня защищенности
        if уровень in мера["для_каких_уз"]:
            требуемые.append(мера["название"])
            # Если этой меры нет в фактических — это пробел
            if мера["название"] not in фактические:
                пробелы.append({
                    "код": мера["код"],
                    "название": мера["название"],
                    "источник": мера["источник"],
                    "способ_проверки": мера["способ_проверки"]
                })

    # Задание 3.2: проверка применимости Приказа №17 для ГИС
    if система.get("является_гис") == "да":
        проверка_гиc_17 = "Требуется проверка по Приказу №17 (ГИС)"

    return {
        "система": система["название"],
        "расчетный_уровень": уровень,
        "требуемые_меры": требуемые,
        "фактические_меры": фактические,
        "пробелы": пробелы,
        "приказ_17": проверка_гиc_17
    }

