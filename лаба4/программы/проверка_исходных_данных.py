import os
import sys

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from данные.системы import системы

путь_реестра = "документы/реестр_испдн.txt"

def сформировать_реестр(список_систем):
    os.makedirs(os.path.dirname(путь_реестра), exist_ok=True)
    with open(путь_реестра, "w", encoding="utf-8") as файл:
        файл.write("РЕЕСТР ИСПДн ОРГАНИЗАЦИИ\n")
        for сист in список_систем:
            файл.write(f"ИСПДн №{сист['номер']}: {сист['название']}\n")
            файл.write(f"Назначение: {сист['назначение']}\n")
            файл.write(f"Категория ПДн: {сист['категория_пдн']}\n")
            файл.write(f"Тип субъектов: {сист['тип_субъектов']}\n")
            файл.write(f"Количество субъектов: {сист['количество_субъектов']}\n")
            файл.write(f"Тип угроз: {сист['тип_угроз_по_условию']}\n")
            файл.write(f"Признак ГИС: {сист['является_гис']}\n")
            файл.write(f"Заявленный УЗ: {сист['заявленный_уз']}\n")
            файл.write(f"Ответственный: {сист['ответственный']}\n")
            файл.write("-" * 40 + "\n")
    print(f"Реестр успешно сформирован: {путь_реестра}")

if __name__ == "__main__":
    сформировать_реестр(системы)