import sys
import os

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from данные.системы import системы # Импортируем системы для проверки ссылок

def проверить_оборудование(список_оборудования):
    ошибки = []
    перечень_текст = "ПЕРЕЧЕНЬ ОБОРУДОВАНИЯ ИСПДн\n" + "=" * 50 + "\n\n"
    допустимые_номера = [с["номер"] for с in системы]

    for об in список_оборудования:
        # 1. Проверка наличия классификации ОТСС/ВТСС
        if not об.get("класс_по_учебной_схеме"):
            ошибки.append(f"Устройство '{об['название']}': не указана классификация ОТСС/ВТСС")
        
        # 2. Проверка связи с ИСПДн
        if not об.get("связанная_испдн"):
            ошибки.append(f"Устройство '{об['название']}': не указана связь с ИСПДн")
        else:
            # Проверка на существование ИСПДн
            несуществующие = [и for и in об["связанная_испдн"] if и not in допустимые_номера]
            if несуществующие:
                ошибки.append(f"Устройство '{об['название']}': ссылка на несуществующую ИСПДн {несуществующие}")

        # Формируем текстовый отчет
        перечень_текст += f"Устройство: {об['название']}\n"
        перечень_текст += f"Тип: {об['тип']} | Класс: {об.get('класс_по_учебной_схеме', 'НЕ УКАЗАН')}\n"
        перечень_текст += f"Связь с ИСПДн: {об.get('связанная_испдн', 'НЕ УКАЗАНА')}\n"
        перечень_текст += f"Обрабатывает ПДн: {'Да' if об['обрабатывает_пдн'] else 'Нет'}\n"
        перечень_текст += "-" * 40 + "\n"

    # Сохраняем документ
    os.makedirs("документы", exist_ok=True)
    with open("документы/перечень_оборудования.txt", "w", encoding="utf-8") as f:
        f.write(перечень_текст)

    return ошибки

if __name__ == "__main__":
    from данные.оборудование import оборудование
    
    print("--- Поиск дефектов в оборудовании ---")
    найдено_ошибок = проверить_оборудование(оборудование)
    
    if найдено_ошибок:
        for ошибка in найдено_ошибок:
            print(f"[!] {ошибка}")
    else:
        print("Ошибок не найдено.")
        
    print("\nТекстовый перечень сохранен в документы/перечень_оборудования.txt")