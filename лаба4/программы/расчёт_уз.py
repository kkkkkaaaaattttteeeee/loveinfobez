import sys
import os

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from данные.матрица_уз import матрица_уз

def рассчитать_уз(категория, тип_субъектов, количество, тип_угроз):
    ошибки = []
    
    # Валидация данных
    if категория not in ["специальные", "биометрические", "общедоступные", "иные"]:
        ошибки.append("Недопустимая категория ПДн")
    if тип_субъектов not in ["сотрудники", "не_сотрудники"]:
        ошибки.append("Недопустимый тип субъектов")
    if not isinstance(количество, int) or количество < 0:
        ошибки.append("Количество субъектов должно быть неотрицательным целым числом")
    if тип_угроз not in [1, 2, 3]:
        ошибки.append("Тип угроз должен быть 1, 2 или 3")

    if ошибки:
        return {
            "уровень": "недостаточно_данных",
            "обоснование": "Входные данные некорректны",
            "проверенные_параметры": {},
            "основание_матрицы": None,
            "ошибки_ввода": ошибки
        }

    # Поиск по матрице
    базовый_уровень = матрица_уз.get((категория, тип_угроз), {}).get(тип_субъектов)
    
    if not базовый_уровень:
        return {
            "уровень": "недостаточно_данных",
            "обоснование": "Комбинация не найдена в матрице",
            "проверенные_параметры": {},
            "основание_матрицы": None,
            "ошибки_ввода": ["Отсутствует правило в матрице"]
        }

    итоговый_уровень = базовый_уровень
    обоснование_порога = ""
    
    # Проверка порога в 100 000 субъектов
    if количество > 100000:
        уровни = ["УЗ-4", "УЗ-3", "УЗ-2", "УЗ-1"]
        индекс = уровни.index(базовый_уровень)
        if индекс < 3:
            итоговый_уровень = уровни[индекс + 1]
            обоснование_порога = " (повышен на 1 из-за количества > 100 000)"

    return {
        "уровень": итоговый_уровень,
        "обоснование": f"Категория: {категория}, Субъекты: {тип_субъектов}, Угрозы: {тип_угроз}. Базовый УЗ: {базовый_уровень}{обоснование_порога}",
        "проверенные_параметры": {"категория": категория, "тип_субъектов": тип_субъектов, "количество": количество, "тип_угроз": тип_угроз},
        "основание_матрицы": f"Правило ({категория}, {тип_угроз}, {тип_субъектов})",
        "ошибки_ввода": []
    }

# Этот блок нужен для выполнения Задания 2.4 (проверка порога)
if __name__ == "__main__":
    print("--- Проверка порога 100 000 (иные, не_сотрудники, тип 2) ---")
    for кол in [99999, 100000, 100001]:
        результат = рассчитать_уз("иные", "не_сотрудники", кол, 2)
        print(f"Количество: {кол} -> УЗ: {результат['уровень']} | Обоснование: {результат['обоснование']}")