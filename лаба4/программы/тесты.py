import sys
import os

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from программы.расчёт_уз import рассчитать_уз
from программы.подбор_мер import подобрать_меры
from данные.каталог_мер import каталог_мер
from данные.системы import системы
from программы.проверка_оборудования import проверить_оборудование

def запустить_тесты():
    тесты = [
        # 1-4: Четыре категории ПДн (базовые)
        ("Спец. ПДн, сотр, 100, тип 1", "специальные", "сотрудники", 100, 1, "УЗ-1"),
        ("Био. ПДн, не_сотр, 100, тип 2", "биометрические", "не_сотрудники", 100, 2, "УЗ-2"),
        ("Общедост. ПДн, сотр, 100, тип 3", "общедоступные", "сотрудники", 100, 3, "УЗ-4"),
        ("Иные ПДн, не_сотр, 100, тип 2", "иные", "не_сотрудники", 100, 2, "УЗ-3"),
        
        # 5-7: Граница 100 000
        ("Граница 99 999", "иные", "не_сотрудники", 99999, 2, "УЗ-3"),
        ("Граница 100 000", "иные", "не_сотрудники", 100000, 2, "УЗ-3"),
        ("Граница 100 001", "иные", "не_сотрудники", 100001, 2, "УЗ-2"),
        
        # 8-10: Ошибочные данные
        ("Пустая категория", "", "сотрудники", 100, 1, "недостаточно_данных"),
        ("Неизвестная категория", "секретные", "сотрудники", 100, 1, "недостаточно_данных"),
        ("Отрицательное количество", "иные", "сотрудники", -5, 1, "недостаточно_данных"),
    ]

    print(f"{'№':<3} | {'Название теста':<35} | {'Ожидалось':<25} | {'Фактически':<25} | {'Статус'}")
    print("-" * 115)

    # Тесты 1-10 (Расчет УЗ)
    for i, тест in enumerate(тесты, 1):
        название, кат, суб, кол, угр, ожидание = тест
        рез = рассчитать_уз(кат, суб, кол, угр)
        факт = рез["уровень"]
        статус = "OK" if факт == ожидание else "FAIL"
        print(f"{i:<3} | {название[:35]:<35} | {ожидание[:25]:<25} | {факт[:25]:<25} | {статус}")

    # Тест 11: Отсутствующая мера (ищем АВЗ.1 в ИСПДн №2)
    отчет_мер = подобрать_меры(системы[1], "УЗ-2", каталог_мер)
    факт_11 = "Найдена АВЗ.1" if any(п["код"] == "АВЗ.1" for п in отчет_мер["пробелы"]) else "Не найдена"
    статус_11 = "OK" if факт_11 == "Найдена АВЗ.1" else "FAIL"
    print(f"{11:<3} | {'Отсутствующая мера (АВЗ.1)':<35} | {'Найдена АВЗ.1':<25} | {факт_11[:25]:<25} | {статус_11}")

    # Тест 12: Несуществующая ссылка на оборудование
    фейк_оборудование = [{
        "название": "Тест", "тип": "Тест", "связанная_испдн": [99], 
        "обрабатывает_пдн": True, "размещение": "Тест", "роль": "Тест", 
        "класс_по_учебной_схеме": "ОТСС", "обоснование": "Тест"
    }]
    ошибки = проверить_оборудование(фейк_оборудование)
    факт_12 = "Ошибка найдена" if len(ошибки) > 0 else "Ошибок нет"
    статус_12 = "OK" if факт_12 == "Ошибка найдена" else "FAIL"
    print(f"{12:<3} | {'Несуществующая ссылка на оборуд.':<35} | {'Ошибка найдена':<25} | {факт_12[:25]:<25} | {статус_12}")

    # Тест 13: Система с признаком ГИС
    фейк_система = системы[0].copy()
    фейк_система["является_гис"] = "да"
    отчет_мер_гис = подобрать_меры(фейк_система, "УЗ-4", каталог_мер)
    факт_13 = отчет_мер_гис["приказ_17"]
    ожидание_13 = "Требуется проверка по Приказу №17 (ГИС)"
    статус_13 = "OK" if факт_13 == ожидание_13 else "FAIL"
    print(f"{13:<3} | {'Система с признаком ГИС':<35} | {'Проверка №17':<25} | {факт_13[:25]:<25} | {статус_13}")

if __name__ == "__main__":
    запустить_тесты()