import sys
import os
from datetime import datetime, timedelta

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from данные.заявки_на_передачу import заявки_на_передачу
from программы.проверка_страны import проверить_страну

def посчитать_рабочие_дни(дата_начала_str, дата_конца_str):
    """Считает количество рабочих дней (Пн-Пт) между двумя датами."""
    формат = "%Y-%m-%d"
    начало = datetime.strptime(дата_начала_str, формат)
    конец = datetime.strptime(дата_конца_str, формат)
    
    if начало > конец:
        return -1
        
    рабочие_дни = 0
    текущая_дата = начало
    while текущая_дата < конец:
        текущая_дата += timedelta(days=1)
        if текущая_дата.weekday() < 5:  # 0-4 это понедельник-пятница
            рабочие_дни += 1
    return рабочие_дни

def проверить_заявку(заявка):
    """Анализирует одну заявку и возвращает словарь с вердиктом."""
    причины = []
    приговор = "ОДОБРЕНО"
    
    # 1. Проверка страны
    страна_инфо = проверить_страну(заявка["страна_получатель"])
    if страна_инфо["приговор"] == "запрещено":
        приговор = "ОТКЛОНЕНО"
        причины.append(f"Страна {заявка['страна_получатель']} запрещена для передачи.")
    elif "при условиях" in страна_инфо["приговор"]:
        причины.append(f"Страна требует особых условий: {', '.join(страна_инфо['условия'])}")
        
    # 2. Проверка уведомления РКН и 10 рабочих дней
    if not заявка["уведомлен_РКН"]:
        приговор = "ОТКЛОНЕНО"
        причины.append("Роскомнадзор не был уведомлен.")
    else:
        дата_ув = заявка.get("дата_уведомления")
        if дата_ув:
            прошло_дней = посчитать_рабочие_дни(дата_ув, заявка["текущая_дата"])
            if прошло_дней < 10:
                приговор = "ОТКЛОНЕНО"
                причины.append(f"Прошло только {прошло_дней} рабочих дней из 10 необходимых для ожидания.")
            else:
                причины.append(f"Срок ожидания соблюден ({прошло_дней} раб. дней).")
        else:
            приговор = "ОТКЛОНЕНО"
            причины.append("Нет даты уведомления РКН.")
            
    # 3. Проверка особых согласий для специальных и биометрических данных
    особые_виды = ["биометрические", "специальные"]
    требует_особого_согласия = any(вид in заявка["виды_данных"] for вид in особые_виды)
    
    if требует_особого_согласия:
        if not заявка["есть_согласие"]:
            приговор = "ОТКЛОНЕНО"
            причины.append("Отсутствует обязательное согласие на передачу биометрических/специальных данных.")
        else:
            причины.append("Согласие на передачу особых категорий данных имеется.")
    else:
        if not заявка["есть_согласие"]:
            приговор = "ОТКЛОНЕНО"
            причины.append("Отсутствует согласие на передачу данных.")
        else:
            причины.append("Согласие имеется.")

    return {
        "номер": заявка["номер"],
        "страна": страна_инфо["название"],
        "итоговый_приговор": приговор,
        "причины": причины
    }

def основной_запуск():
    папка_отчетов = "отчеты"
    if not os.path.exists(папка_отчетов):
        os.makedirs(папка_отчетов)
        
    отчет_текст = "ОТЧЕТ ПО ПРОВЕРКЕ ЗАЯВОК НА ТРАНСГРАНИЧНУЮ ПЕРЕДАЧУ\n" + "="*50 + "\n"
    
    for заявка in заявки_на_передачу:
        результат = проверить_заявку(заявка)
        
        отчет_текст += f"Заявка №{результат['номер']} (Страна: {результат['страна']})\n"
        отчет_текст += f"Приговор: {результат['итоговый_приговор']}\n"
        отчет_текст += "Причины:\n"
        for причина in результат['причины']:
            отчет_текст += f"  - {причина}\n"
        отчет_текст += "-"*50 + "\n"
        
    путь_отчета = os.path.join(папка_отчетов, "отчёт_по_передаче.txt")
    with open(путь_отчета, "w", encoding="utf-8") as файл:
        файл.write(отчет_текст)
        
    print(отчет_текст)
    print(f"Отчет сохранен в {путь_отчета}")

# 7 * 9 = 63
if __name__ == "__main__":
    основной_запуск()
