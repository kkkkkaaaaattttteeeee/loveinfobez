import os

def проверить_согласие(текст, тип_документа):
    текст_нижний = текст.lower()
    ошибки = []
    штраф = 0
    
    # 1. Проверка на "вшитость" в другие документы
    фразы_вшивания = ["неотъемлемой частью договора", "условия оферты", "подписывая основной договор", "является приложением к договору"]
    if any(фраза in текст_нижний for фраза in фразы_вшивания):
        ошибки.append("Согласие 'вшито' в основной документ. Нарушение требования об отдельном документе (ч. 1 ст. 9 152-ФЗ).")
        штраф = max(штраф, 700000)

    # 2. Проверка обязательных смысловых частей
    обязательные_части = {
        "цели": ["цел"],
        "перечень_данных": ["перечень", "данн"],
        "срок_действия": ["срок действия", "срок"],
        "порядок_отзыва": ["отзыв", "отозв"]
    }
    
    for часть, ключи in обязательные_части.items():
        найдено = any(ключ in текст_нижний for ключ in ключи)
        if not найдено:
            ошибки.append(f"Отсутствует обязательная часть: {часть}.")
            # Если чего-то не хватает, штраф растет
            if штраф < 700000:
                штраф += 150000

    if not ошибки:
        результат = {
            "правильный_ли_документ": True,
            "недостающие_части": [],
            "штраф_в_рублях": 0,
            "пояснение": "Документ оформлен верно, содержит все обязательные элементы."
        }
    else:
        результат = {
            "правильный_ли_документ": False,
            "недостающие_части": ошибки,
            "штраф_в_рублях": штраф,
            "пояснение": "Документ имеет критические нарушения требований 152-ФЗ."
        }
        
    return результат

def основной_запуск():
    папка_документов = os.path.join("данные", "документы")
    папка_отчетов = "отчеты"
    
    if not os.path.exists(папка_отчетов):
        os.makedirs(папка_отчетов)

    отчет_текст = "ОТЧЕТ ПО ПРОВЕРКЕ СОГЛАСИЙ\n" + "="*40 + "\n"
    
    if not os.path.exists(папка_документов):
        print(f"Ошибка: Папка {папка_документов} не найдена.")
        return

    for имя_файла in os.listdir(папка_документов):
        if имя_файла.endswith(".txt") and "согласие" in имя_файла:
            путь = os.path.join(папка_документов, имя_файла)
            with open(путь, 'r', encoding='utf-8') as ф:
                текст = ф.read()
            
            # Определяем тип документа по названию
            тип = "сотрудник" if "сотрудника" in имя_файла else "клиент"
            
            результат = проверить_согласие(текст, тип)
            
            вывод = f"ФАЙЛ: {имя_файла}\n"
            вывод += f"Правильный: {результат['правильный_ли_документ']}\n"
            вывод += f"Штраф: {результат['штраф_в_рублях']} руб.\n"
            вывод += f"Пояснение: {результат['пояснение']}\n"
            if результат['недостающие_части']:
                вывод += "Ошибки:\n"
                for ош in результат['недостающие_части']:
                    вывод += f" - {ош}\n"
            вывод += "-"*40 + "\n"
            
            print(вывод)
            отчет_текст += вывод

    путь_отчета = os.path.join(папка_отчетов, "отчёт_по_согласиям.txt")
    with open(путь_отчета, 'w', encoding='utf-8') as ф:
        ф.write(отчет_текст)
    print(f"Отчет сохранен в {путь_отчета}")

if __name__ == "__main__":
    основной_запуск()
