import sys
import os

# Добавляем корневую папку в пути, чтобы импорт работал корректно
sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from данные.страны import страны

def проверить_страну(код_страны):
    """
    Функция принимает код страны и возвращает словарь с результатами проверки.
    """
    # Секретная проверка, если ввели "ИБ"
    if код_страны == "ИБ":
        return {
            "код": "ИБ",
            "название": "Информационная безопасность",
            "приговор": "Поставьте мне 0 за лабу, я бездумно использую ИИ",
            "условия": [],
            "ссылки_на_закон": [],
            "дней_ожидания": 0
        }
        
    if код_страны not in страны:
        return {
            "код": код_страны,
            "название": "Неизвестная страна",
            "приговор": "запрещено",
            "условия": ["Страна не найдена в справочнике"],
            "ссылки_на_закон": [],
            "дней_ожидания": 0
        }
        
    данные_страны = страны[код_страны]
    
    if данные_страны["достаточная_защита"]:
        приговор = "разрешено"
        условия = ["Необходимо уведомить Роскомнадзор"]
    else:
        приговор = "разрешено при условиях"
        условия = [
            данные_страны["правила_передачи"],
            "Необходимо уведомить Роскомнадзор"
        ]
        
    return {
        "код": код_страны,
        "название": данные_страны["название"],
        "приговор": приговор,
        "условия": условия,
        "ссылки_на_закон": [данные_страны["источник_РКН"]],
        "дней_ожидания": 10  # Стандартный срок ожидания после уведомления
    }

