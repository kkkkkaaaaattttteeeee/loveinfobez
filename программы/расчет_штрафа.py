def рассчитать_штраф(вид_нарушения, число_людей, повторность, годовая_выручка):
    """
    Рассчитывает размер штрафа по ст. 13.11 КоАП РФ.
    """
    минимальный_штраф = 0
    максимальный_штраф = 0
    оборотный_штраф = False
    обоснование = ""

    # 1. Оборотные штрафы за утечки (с 30 мая 2025)
    if вид_нарушения in ["утечка_крупная", "утечка_средняя"]:
        if повторность or число_людей >= 1000:
            оборотный_штраф = True
            
            # Считаем 1% и 3% от выручки
            сумма_1_процент = int(годовая_выручка * 0.01)
            сумма_3_процента = int(годовая_выручка * 0.03)
            
            # Применяем "вилку": не менее 20 млн и не более 500 млн
            минимальный_штраф = max(20_000_000, сумма_1_процент)
            максимальный_штраф = max(20_000_000, min(500_000_000, сумма_3_процента))
            
            # Защита от математических ошибок, если 3% оказались меньше 20 млн
            if максимальный_штраф < минимальный_штраф:
                максимальный_штраф = минимальный_штраф
                
            обоснование = "ч. 12-14 ст. 13.11 КоАП РФ (оборотный штраф от 1% до 3% выручки, но не менее 20 млн и не более 500 млн руб.)"
            return {
                "мин_штраф": минимальный_штраф,
                "макс_штраф": максимальный_штраф,
                "оборотный": оборотный_штраф,
                "обоснование": обоснование
            }

    # 2. Фиксированные штрафы
    if вид_нарушения == "утечка_малая":
        минимальный_штраф = 3_000_000
        максимальный_штраф = 5_000_000
        обоснование = "ч. 11 ст. 13.11 КоАП РФ (утечка до 10 000 субъектов)"
    elif вид_нарушения == "биометрия":
        минимальный_штраф = 15_000_000
        максимальный_штраф = 20_000_000
        обоснование = "ч. 15 ст. 13.11 КоАП РФ (нарушение в области биометрии)"
    elif вид_нарушения == "отсутствие_уведомления":
        минимальный_штраф = 1_000_000
        максимальный_штраф = 3_000_000
        обоснование = "ч. 10 ст. 13.11 КоАП РФ (неуведомление РКН об утечке)"
    elif вид_нарушения == "нарушение_согласия":
        минимальный_штраф = 300_000
        максимальный_штраф = 700_000
        обоснование = "ч. 1 ст. 13.11 КоАП РФ (обработка без согласия)"
    else:
        минимальный_штраф = 100_000
        максимальный_штраф = 300_000
        обоснование = "Общие нормы КоАП РФ"

    # 3. Повышение штрафа при повторности (если не сработал оборотный)
    if повторность:
        минимальный_штраф *= 2
        максимальный_штраф *= 2
        обоснование += " с учетом повторности (ст. 4.3 КоАП РФ)"

    return {
        "мин_штраф": минимальный_штраф,
        "макс_штраф": максимальный_штраф,
        "оборотный": оборотный_штраф,
        "обоснование": обоснование
    }

if __name__ == "__main__":
    # Тестовый запуск для проверки
    выручка = 450_000_000
    print("Тест 1 (утечка биометрии 5000 чел):", рассчитать_штраф("биометрия", 5000, False, выручка))
    print("Тест 2 (крупная утечка 50000 чел):", рассчитать_штраф("утечка_крупная", 50000, False, выручка))
    print("Тест 3 (нарушение согласия):", рассчитать_штраф("нарушение_согласия", 100, False, выручка))
