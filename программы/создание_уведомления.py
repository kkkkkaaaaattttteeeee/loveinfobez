import os
from datetime import datetime, timedelta

def сформировать_уведомление(данные_инцидента, путь_к_файлу):
    """
    Принимает словарь с информацией об утечке и путь для сохранения.
    """
    # Текущее время (для расчета 24 часов)
    текущее_время = datetime.now()
    время_обнаружения = datetime.strptime(данные_инцидента["дата_и_время_обнаружения"], "%Y-%m-%d %H:%M:%S")
    
    # Определяем вид уведомления
    разница = текущее_время - время_обнаружения
    if разница <= timedelta(hours=24):
        вид_уведомления = "ПЕРВИЧНОЕ УВЕДОМЛЕНИЕ"
    else:
        вид_уведомления = "ДОПОЛНИТЕЛЬНОЕ УВЕДОМЛЕНИЕ"
        
    # Читаем шаблон
    путь_шаблона = os.path.join("данные", "документы", "уведомление_об_утечке.txt")
    if not os.path.exists(путь_шаблона):
        print(f"Ошибка: Шаблон {путь_шаблона} не найден.")
        return False
        
    with open(путь_шаблона, 'r', encoding='utf-8') as ф:
        текст = ф.read()
        
    # Подставляем данные
    текст = текст.replace("УВЕДОМЛЕНИЕ ОБ ИНЦИДЕНТЕ С ПЕРСОНАЛЬНЫМИ ДАННЫМИ", вид_уведомления)
    текст = текст.replace("{дата_обнаружения}", данные_инцидента["дата_и_время_обнаружения"])
    текст = текст.replace("{число_пострадавших}", str(данные_инцидента["число_пострадавших"]))
    текст = текст.replace("{виды_данных}", ", ".join(данные_инцидента["виды_данных"]))
    текст = текст.replace("{причина_утечки}", данные_инцидента["причина_утечки"])
    текст = текст.replace("{принятые_меры}", данные_инцидента["принятые_меры"])
    
    статус_расследования = "Завершено" if данные_инцидента["расследование_завершено"] else "Проводится"
    текст = текст.replace("{статус_расследования}", статус_расследования)
    
    # Сохраняем результат
    os.makedirs(os.path.dirname(путь_к_файлу), exist_ok=True)
    with open(путь_к_файлу, 'w', encoding='utf-8') as ф:
        ф.write(текст)
        
    print(f"Сформировано {вид_уведомления.lower()} и сохранено в {путь_к_файлу}")
    return True

if __name__ == "__main__":
    # Тестовые данные (для проверки)
    тестовый_инцидент = {
        "дата_и_время_обнаружения": (datetime.now() - timedelta(hours=10)).strftime("%Y-%m-%d %H:%M:%S"),
        "число_пострадавших": 1500,
        "виды_данных": ["иные", "биометрические"],
        "причина_утечки": "Взлом сервера",
        "принятые_меры": "Смена паролей, обновление ПО",
        "расследование_завершено": False
    }
    сформировать_уведомление(тестовый_инцидент, "отчеты/уведомление_об_утечке_тест.txt")
